//! What:
//!  A Dylint late lint that reports a closure unless it captures something and is handed to a callee that keeps it.
//! Why:
//!  A closure that captures nothing can be a named function,
//!  and a closure that only lends its captures for the duration of a call can be a loop or a named function with parameters;
//!  only a closure that owns state for a callee requiring `'static` has no named replacement.
//!
//! In TS you'd write (pseudocode):
//! ```ts
//! for (const closure of allClosures(crate)) {
//!   if (!(capturesSomething(closure) && isDirectArgumentOfStaticParameter(closure))) report(closure);
//! }
//! ```
