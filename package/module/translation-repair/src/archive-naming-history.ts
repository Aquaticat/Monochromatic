import { tagged, } from '@monochromatic-dev/module-logger/ts';
import { archiveCommitParents, } from './archive-commit-parents.ts';
import {
  type ArchiveDiffHunk,
  archiveDiffHunks,
} from './archive-diff-hunks.ts';
import { ArchiveNamingEvidenceError, } from './archive-naming-error.ts';
import { archiveGitOutput, } from './archive-naming-git.ts';
import type { ArchiveNamingScope, } from './archive-naming-scope.ts';
import type { CorpusPin, } from './corpus-source.ts';
import { mapOverlapped, } from './overlapped-map.ts';

//region Origin revision reads
// A single parent and ordinary same-path diff are prerequisites, not naming proof.

/**
 * Naming history logger.
 */
const l = tagged({ tag: 'archive-naming-history', },);

/**
 * Exact ordinary diff from the sole predecessor of one origin.
 *
 * @example
 * ```ts
 * const history = histories.get(scope.origin.commit);
 * ```
 */
export type ArchiveRevisionHistory = {
  /**
   * Sole actual predecessor.
   */
  readonly parentCommit: string;
  /**
   * Exact zero-context hunks for the requested path.
   */
  readonly hunks: readonly ArchiveDiffHunk[];
};

/**
 * Reads each needed origin once, without relying on author summaries or semantic diffs.
 *
 * @param scopes - unique initial-reference line mappings
 *
 * @param pin - pinned corpus context
 *
 * @param relPath - same literal archive path throughout acquisition
 *
 * @param signal - shared cancellation
 *
 * @returns Ordinary origin histories plus explicit root/merge withholding
 *
 * @throws {@link ArchiveNamingEvidenceError} for failed reads or malformed provenance
 *
 * @example
 * ```ts
 * const { histories } = await readArchiveNamingHistories({ scopes, pin, relPath });
 * ```
 */
export async function readArchiveNamingHistories({
  scopes,
  pin,
  relPath,
  signal,
}: {
  readonly scopes: readonly ArchiveNamingScope[];
  readonly pin: CorpusPin;
  readonly relPath: string;
  readonly signal?: AbortSignal;
},): Promise<{
  readonly histories: ReadonlyMap<string, ArchiveRevisionHistory>;
  readonly findings: readonly string[];
}> {
  /**
   * Function-scoped operation logger.
   */
  const rl = tagged({
    tag: readArchiveNamingHistories.name,
    l,
  },);
  /**
   * Explicit roots and merges do not qualify as one naming replacement.
   */
  const findings: string[] = [];
  /**
   * Completed histories are shared by all occurrences in the same origin.
   */
  const histories = new Map<string, ArchiveRevisionHistory>();
  /**
   * Origin set is fixed before I/O, never generated by reviewer feedback.
   */
  const commits = new Set(scopes.map(function originCommit(scope,): string {
    return scope.origin
      .commit;
  },),);
  await mapOverlapped({
    items: [...commits],
    overlap: 1,
    oneItem: async function readOrigin({ item: commit, },): Promise<void> {
    /**
     * Intrinsic commit object, not an effective grafted parent rendering.
     */
    const parentText = await archiveGitOutput({
      pin,
      relPath,
      args: [
        'cat-file',
        'commit',
        commit
      ],
      ...(signal === undefined ? {} : { signal, }),
    },);
    /**
     * Only intrinsic consecutive parent headers establish root or merge cardinality.
     */
    const parents = archiveCommitParents({ object: parentText, relPath, },);
    if (parents.length !== 1) {
      findings.push(`archive-revision-withheld (${commit}: root or merge origin)`,);
      rl.debug(`withheld origin with ${String(parents.length,)} parents`,);
      return;
    }
    /**
     * Sole predecessor after explicit cardinality validation.
     */
    const [parentCommit,] = parents;
    if (parentCommit === undefined)
      throw new ArchiveNamingEvidenceError({
        kind: 'history-shape',
        relPath,
      },);
    // A blame origin must actually be an ancestor; failure is inconsistent provenance.
    await archiveGitOutput({
      pin,
      relPath,
      args: [
        'merge-base',
        '--is-ancestor',
        commit,
        pin.commitSha
      ],
      ...(signal === undefined ? {} : { signal, }),
    },);
    /**
     * Complete ordinary patch; local diff formatting and drivers cannot rewrite it.
     */
    const patch = await archiveGitOutput({
      pin,
      relPath,
      args: [
        'diff',
        '--unified=0',
        '--no-ext-diff',
        '--no-textconv',
        '--no-renames',
        '--no-color',
        '--diff-algorithm=myers',
        '--no-indent-heuristic',
        '--inter-hunk-context=0',
        '--output-indicator-new=+',
        '--output-indicator-old=-',
        '--output-indicator-context= ',
        '--line-prefix=',
        parentCommit,
        commit,
        '--',
        relPath,
      ],
      ...(signal === undefined ? {} : { signal, }),
    },);
    histories.set(
      commit,
      {
        parentCommit,
        hunks: archiveDiffHunks({
          patch,
          relPath,
        },),
      },
    );
    },
  },);
  rl.debug(`read ${String(histories.size,)} ordinary origins`,);
  return {
    histories,
    findings,
  };
}

//endregion Origin revision reads
