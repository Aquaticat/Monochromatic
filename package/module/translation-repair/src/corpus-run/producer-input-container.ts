import { producerInputChildEnvironment, PRODUCER_INPUT_HOSTNAME, } from './producer-input-environment.ts';
import type { ProducerInputLaunch, } from './producer-input-model.ts';
import { PRODUCER_INPUT_PATHS, } from './producer-input-paths.ts';

//region Fixed no-network input container contract

/**
 * Only the owning host path inserts this private child-mode sentinel.
 */
export const PRODUCER_INPUT_CHILD_SENTINEL = '--sealed-preparation-child';
/**
 * Host and child agree on one bounded reconstruction envelope.
 */
export const PRODUCER_INPUT_LIMITS = {
  /**
   * Hard resident-memory allowance, unchanged from provider-free semantic verification.
   */
  memoryBytes: 2_147_483_648,
  /**
   * Combined memory-plus-swap value requests the previously measured 2 GiB swap allowance.
   */
  memoryAndSwapBytes: 4_294_967_296,
  /**
   * CPU quota uses Podman's standard period.
   */
  cpuQuota: 200_000,
  /**
   * Explicit period makes the child observation unambiguous.
   */
  cpuPeriod: 100_000,
  /**
   * Process count remains independent of input cardinality.
   */
  pids: 512,
  /**
   * A stopped host cannot leave an unbounded reconstruction container.
   */
  seconds: 300,
  /**
   * Temporary storage is not another input or runtime mount.
   */
  temporaryBytes: 67_108_864,
} as const;
/**
 * Fixed bind-mount role values remain deeply readonly through argument construction.
 *
 * @example
 * ```ts
 * const mount: ProducerInputBindMount = { source, target: '/runtime', writable: false };
 * ```
 */
type ProducerInputBindMount = {
  /**
   * Independently authorized host locator.
   */
  readonly source: string;
  /**
   * Fixed container role location.
   */
  readonly target: string;
  /**
   * Only the private output role permits writes.
   */
  readonly writable: boolean;
};

/**
 * Encodes Podman's CSV mount grammar at the final syntax boundary.
 * Quoting whole fields preserves commas, quotes, equals, colons and newlines in host locators.
 *
 * @param source - independently authorized host path
 *
 * @param target - fixed container role path
 *
 * @param writable - only the private output role may be writable
 *
 * @returns One native --mount argument, never a shell command
 *
 * @example
 * ```ts
 * const mount = producerInputMount({ source, target: '/runtime', writable: false });
 * ```
 */
function producerInputMount({
  source,
  target,
  writable,
}: ProducerInputBindMount,): string {
  return [
    'type=bind',
    `source=${source}`,
    `target=${target}`,
    writable ? 'rw' : 'ro'
  ]
    .map(function quoted(field): string { return `"${field.replaceAll(
      '"',
      '""'
    )}"`; })
    .join(',');
}

/**
 * Constructs only the dedicated input-reconstruction container invocation.
 * Callers cannot replace its application, command, network mode, resources or environment vocabulary.
 *
 * @param launch - validated independently identified launch
 *
 * @param nodePath - executing host Node after identity verification
 *
 * @param bootstrapPath - executing single-file bootstrap after identity verification
 *
 * @param launchSnapshotPath - exclusive immutable launch snapshot outside writable child output
 *
 * @param outputPath - newly created private host output directory
 *
 * @param containerIdPath - new host control-file locator for observed container identity
 *
 * @param runId - exclusive input-run identity generated by the host
 *
 * @param launchSha256 - independently recorded raw launch digest
 *
 * @param launchBytes - independently recorded raw launch extent
 *
 * @param callerUid - host owner to verify after namespace mapping
 *
 * @param callerGid - host group identity checked independently from UID
 *
 * @returns Native Podman argument vector without shell interpolation
 *
 * @example
 * ```ts
 * const args = producerInputContainerArgs({ launch, nodePath, bootstrapPath, launchSnapshotPath, outputPath, containerIdPath, runId, launchSha256, launchBytes, callerUid, callerGid });
 * ```
 */
export function producerInputContainerArgs({
  launch,
  nodePath,
  bootstrapPath,
  launchSnapshotPath,
  outputPath,
  containerIdPath,
  runId,
  launchSha256,
  launchBytes,
  callerUid,
  callerGid,
}: {
  readonly launch: ProducerInputLaunch;
  readonly nodePath: string;
  readonly bootstrapPath: string;
  readonly launchSnapshotPath: string;
  readonly outputPath: string;
  readonly containerIdPath: string;
  readonly runId: string;
  readonly launchSha256: string;
  readonly launchBytes: number;
  readonly callerUid: number;
  readonly callerGid: number;
},): readonly string[] {
  /**
   * No image or host loader variables survive into child startup.
   */
  const environment = producerInputChildEnvironment({ runId, launchSha256, launchBytes, callerUid, callerGid, });
  /**
   * Fixed requested role mappings must also be checked against the actual created container and child mounts.
   */
  const mounts: readonly ProducerInputBindMount[] = [
    {
      source: nodePath,
      target: PRODUCER_INPUT_PATHS.node,
      writable: false
    },
    {
      source: bootstrapPath,
      target: PRODUCER_INPUT_PATHS.bootstrap,
      writable: false
    },
    {
      source: launchSnapshotPath,
      target: PRODUCER_INPUT_PATHS.launch,
      writable: false
    },
    {
      source: launch.runtime
        .dir,
      target: PRODUCER_INPUT_PATHS.runtime,
      writable: false
    },
    {
      source: launch.atomicLibrary
        .path,
      target: PRODUCER_INPUT_PATHS.atomicLibrary,
      writable: false
    },
    {
      source: launch.selection
        .path,
      target: PRODUCER_INPUT_PATHS.selection,
      writable: false
    },
    {
      source: launch.supporting
        .dir,
      target: PRODUCER_INPUT_PATHS.supporting,
      writable: false
    },
    {
      source: launch.corpus
        .dir,
      target: PRODUCER_INPUT_PATHS.corpus,
      writable: false
    },
    {
      source: outputPath,
      target: PRODUCER_INPUT_PATHS.output,
      writable: true
    },
  ];
  return [
    'run',
    '--pull=never',
    '--name',
    `producer-input-${runId}`,
    '--cidfile',
    containerIdPath,
    '--network=none',
    '--memory',
    String(PRODUCER_INPUT_LIMITS.memoryBytes),
    '--memory-swap',
    String(PRODUCER_INPUT_LIMITS.memoryAndSwapBytes),
    '--cpu-period',
    String(PRODUCER_INPUT_LIMITS.cpuPeriod),
    '--cpu-quota',
    String(PRODUCER_INPUT_LIMITS.cpuQuota),
    '--pids-limit',
    String(PRODUCER_INPUT_LIMITS.pids),
    '--timeout',
    String(PRODUCER_INPUT_LIMITS.seconds),
    '--read-only',
    '--read-only-tmpfs=false',
    '--cap-drop=ALL',
    '--security-opt=no-new-privileges',
    '--security-opt=label=disable',
    '--userns=keep-id',
    '--no-healthcheck',
    '--image-volume=ignore',
    '--systemd=false',
    '--unsetenv-all',
    '--http-proxy=false',
    '--hostname',
    PRODUCER_INPUT_HOSTNAME,
    '--tmpfs',
    `/tmp:rw,noexec,nosuid,nodev,size=${String(PRODUCER_INPUT_LIMITS.temporaryBytes)}`,
    '--workdir',
    PRODUCER_INPUT_PATHS.output,
    '--entrypoint',
    PRODUCER_INPUT_PATHS.node,
    ...Object.entries(environment)
      .flatMap(function env([name, value]): readonly string[] { return [
        '--env',
        `${name}=${value}`
      ]; }),
    ...mounts.flatMap(function mount(value): readonly string[] { return [
      '--mount',
      producerInputMount(value)
    ]; }),
    launch.imageId,
    PRODUCER_INPUT_PATHS.bootstrap,
    PRODUCER_INPUT_CHILD_SENTINEL,
  ];
}

//endregion Fixed no-network input container contract
